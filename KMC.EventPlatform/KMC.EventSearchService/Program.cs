var builder = WebApplication.CreateBuilder(args);

builder.Services.AddControllers();
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen(options =>
{
    options.SwaggerDoc("v1", new() { Title = "KMC Event Search Service", Version = "v1" });
});

builder.Services.AddHttpClient<KMC.EventSearchService.Services.EventServiceClient>(client =>
{
    var baseUrl = builder.Configuration["Services:EventManagementBaseUrl"];
    client.BaseAddress = new Uri(baseUrl!);
});

builder.Services.AddCors(options =>
{
    options.AddPolicy("AllowAll", policy =>
        policy.AllowAnyOrigin().AllowAnyHeader().AllowAnyMethod());
});

var app = builder.Build();

if (app.Environment.IsDevelopment())
{
    app.UseSwagger();
    app.UseSwaggerUI();
}

app.UseCors("AllowAll");
app.MapControllers();

app.Run();
